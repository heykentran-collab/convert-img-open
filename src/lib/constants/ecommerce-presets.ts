/**
 * Get localized version of preset fields based on active locale
 */
export function getLocalizedPreset(preset: EcommercePreset, locale: string): EcommercePreset {
  if (locale === 'en') {
    return {
      ...preset,
      name: preset.nameEn || preset.name,
      platform: preset.platformEn || preset.platform,
      purpose: preset.purposeEn || preset.purpose,
      recommendation: preset.recommendationEn || preset.recommendation,
    };
  }
  return preset;
}

/**
 * Filter presets by search term and selected category
 */
export function filterEcommercePresets(
  presets: EcommercePreset[],
  query: string,
  category: PresetCategory
): EcommercePreset[] {
  let list = presets;
  if (category !== 'all') {
    list = list.filter((p) => p.category === category);
  }

  const q = query.trim().toLowerCase();
  if (!q) return list;

  return list.filter((p) => {
    return (
      p.name.toLowerCase().includes(q) ||
      (p.nameEn && p.nameEn.toLowerCase().includes(q)) ||
      p.platform.toLowerCase().includes(q) ||
      (p.platformEn && p.platformEn.toLowerCase().includes(q)) ||
      p.purpose.toLowerCase().includes(q) ||
      (p.purposeEn && p.purposeEn.toLowerCase().includes(q)) ||
      p.ratio.toLowerCase().includes(q) ||
      String(p.width).includes(q) ||
      String(p.height).includes(q) ||
      `${p.width}x${p.height}`.includes(q) ||
      `${p.width}×${p.height}`.includes(q) ||
      (p.recommendation && p.recommendation.toLowerCase().includes(q)) ||
      (p.recommendationEn && p.recommendationEn.toLowerCase().includes(q))
    );
  });
}
